"""Parser boundaries: frontmatter, fences, indented code, comments and link syntax."""

import pytest

from project_docs.markdown import frontmatter_end, parse
from support import Repo


def _targets(text: str, *, include_code: bool = False) -> list[str]:
    links = parse(text.split("\n")).links
    return [link.target for link in links if include_code or not link.in_code]


def test_frontmatter_hash_lines_are_yaml_comments() -> None:
    lines = ["---", "# generated by a tool", "title: Old", "---", "> banner"]
    assert frontmatter_end(lines) == 4


@pytest.mark.parametrize(
    "text",
    [
        "---\n# Section title\n---\n[x](a.md)",
        "---\n- [x](a.md) - a list between rules\n---",
        "---\nno closing rule\n[x](a.md)",
        " ---\ntype: guide\n---\n[x](a.md)",
        "---\nurl:http://x\n---\n[x](a.md)",
    ],
)
def test_leading_rule_without_keys_is_body(text: str) -> None:
    assert frontmatter_end(text.split("\n")) == 0
    assert _targets(text) == ["a.md"]


def test_bom_before_frontmatter(repo: Repo) -> None:
    (repo.root / "docs" / "archive").mkdir(parents=True)
    path = repo.root / "docs" / "archive" / "old.md"
    path.write_bytes("﻿---\ntitle: Old\n---\n> Historical.\n".encode())
    assert repo.check() == []


def test_fence_closes_only_without_info_string() -> None:
    text = "```bash\ncat <<EOF\n```json\n[a](in-code.md)\n```\n[b](after.md)"
    assert _targets(text) == ["after.md"]


@pytest.mark.parametrize(
    "text",
    [
        "~~~\n[a](x.md)\n```\n[b](x.md)\n~~~\n[c](after.md)",
        "````\n[a](x.md)\n```\n[b](x.md)\n````\n[c](after.md)",
        "   ```\n[a](x.md)\n   ```\n[c](after.md)",
        "1. Run:\n    ```bash\n    echo [a](x.md)\n    ```\n[c](after.md)",
        "- Run:\n\t```\n\t[a](x.md)\n\t```\n[c](after.md)",
        "- Setup\n  - Build:\n      ```sh\n      [a](x.md)\n      ```\n[c](after.md)",
        "> [!NOTE]\n> ```bash\n> [a](x.md)\n> ```\n\n[c](after.md)",
    ],
)
def test_fence_variants(text: str) -> None:
    assert _targets(text) == ["after.md"]


def test_fenced_examples_in_lists_and_alerts_are_not_checked(repo: Repo) -> None:
    repo.write(
        "docs/guide.md",
        "1. Install:\n    ```bash\n    cat [x](missing.md)\n    ```\n"
        "> [!TIP]\n> ```md\n> [y](missing.md)\n> ```\n",
    )
    assert repo.check() == []


def test_backtick_info_string_with_backtick_is_not_a_fence() -> None:
    assert _targets("``` a`b\n[a](x.md)") == ["x.md"]


def test_indented_code_after_blank_line() -> None:
    text = "Para\n\n    - [a](code.md)\n    [b](code2.md)\n\n- item\n    [c](continuation.md)"
    assert _targets(text) == ["continuation.md"]
    assert _targets(text, include_code=True) == ["code.md", "code2.md", "continuation.md"]


def test_indented_list_like_line_is_not_checked(repo: Repo) -> None:
    repo.write("docs/guide.md", "Example:\n\n    - [x](missing.md)\n\t[y](missing.md)\n")
    assert repo.check() == []


def test_inline_code_and_comments_hide_links() -> None:
    text = (
        "`[a](x.md)` and ``[b](`y`.md)``\n"
        "<!-- [c](x.md) --> [d](kept.md)\n"
        "<!--\n[e](x.md)\n-->\n"
        "Use `<!--` to open a comment.\n"
        "[f](after.md)"
    )
    assert _targets(text) == ["kept.md", "after.md"]


@pytest.mark.parametrize(
    "line",
    [
        "<!-- check `foo --> See `bar` and [a](kept.md)",
        "<!-- a ``` b --> [a](kept.md)",
        "`<!--` [a](kept.md) `-->`",
        "Unclosed ` tick, <!-- c --> [a](kept.md)",
    ],
)
def test_comments_and_code_spans_scan_left_to_right(line: str) -> None:
    assert _targets(f"{line}\n[z](after.md)") == ["kept.md", "after.md"]


def test_comment_opener_inside_indented_code_does_not_swallow_text() -> None:
    assert _targets("Para\n\n    <!-- open\n\n[a](after.md)") == ["after.md"]


@pytest.mark.parametrize(
    ("line", "expected"),
    [
        ('[a](x.md "Title")', ["x.md"]),
        ("[a](<my file.md>)", ["<my file.md>"]),
        ("[a](notes(1).md)", ["notes(1).md"]),
        ("[![badge](img.svg)](target.md)", ["target.md"]),
        ("[a] (x.md) is not a link", []),
        ("- [ ] task with [a](x.md)", ["x.md"]),
        ('<a class="c" href="x.md">a</a>', ["x.md"]),
        ("<A HREF='x.md'>a</A>", ["x.md"]),
        ("@docs/a.md and @notes.md, mail me@example.com or @user", ["docs/a.md", "notes.md"]),
        ("[ref]: x.md 'Title'", ["x.md"]),
        ("[^1]: Footnote text.", []),
        ("[Note]: this is prose, not a definition", []),
    ],
)
def test_link_syntax(line: str, expected: list[str]) -> None:
    assert _targets(line) == expected


def test_reference_use_resolves_definition() -> None:
    lines = ["- [Topic][T] text", "- [Other][] text", "", "[t]: a.md", "[other]: b.md"]
    links = parse(lines).links
    assert [(link.kind, link.target) for link in links if link.kind == "ref_use"] == [
        ("ref_use", "a.md"),
        ("ref_use", "b.md"),
    ]
